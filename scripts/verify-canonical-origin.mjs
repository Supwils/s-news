#!/usr/bin/env node

import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { PRODUCTION_ORIGIN } from "../lib/site-origin.mjs";

/**
 * Asserts that the build advertises one origin, and that a production build
 * advertises the real one.
 *
 * Why this is a build gate and not a test: `getSiteUrl()` resolves from the
 * environment, so on a developer's machine it is always right (localhost) and
 * on Vercel it was always wrong — for months, silently. Nothing in the repo
 * could see it. The failure surfaced only by fetching the live site and reading
 * the `<link rel="canonical">` it had been serving to Google.
 *
 * Two assertions:
 *   consistent — every prerendered page and the sitemap agree on one origin.
 *                Runs everywhere, including locally.
 *   correct    — on `VERCEL_ENV=production`, that origin is PRODUCTION_ORIGIN.
 *                A production deploy that would ship the wrong canonical fails
 *                the build instead of shipping it.
 *
 * Runs as `postbuild`, next to verify-build-trace.mjs.
 */

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SERVER_APP_DIR = path.join(PROJECT_ROOT, ".next", "server", "app");

/** Enough prerendered pages to catch a route that resolves its origin differently. */
const HTML_SAMPLE_LIMIT = 200;

function collectHtmlFiles(dir, found = []) {
  if (found.length >= HTML_SAMPLE_LIMIT) return found;
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    if (found.length >= HTML_SAMPLE_LIMIT) break;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) collectHtmlFiles(full, found);
    else if (entry.name.endsWith(".html")) found.push(full);
  }
  return found;
}

function originOf(url) {
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

function fail(lines) {
  console.error("Canonical origin verification FAILED.\n");
  for (const line of lines) console.error(`  ${line}`);
  console.error("");
  process.exit(1);
}

/** origin -> one example file that emitted it */
const origins = new Map();

function record(origin, source) {
  if (origin && !origins.has(origin)) origins.set(origin, source);
}

const htmlFiles = collectHtmlFiles(SERVER_APP_DIR);
if (htmlFiles.length === 0) {
  fail([
    `No prerendered .html under ${path.relative(PROJECT_ROOT, SERVER_APP_DIR)}.`,
    "Did `next build` run? This script is a postbuild step.",
  ]);
}

for (const file of htmlFiles) {
  const html = readFileSync(file, "utf8");
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  record(originOf(canonical ?? ""), path.relative(PROJECT_ROOT, file));
}

// The sitemap is what Google actually crawls, and it is generated by a
// different code path than the page metadata — worth asserting separately.
try {
  const sitemap = readFileSync(path.join(SERVER_APP_DIR, "sitemap.xml.body"), "utf8");
  record(originOf(sitemap.match(/<loc>([^<]+)<\/loc>/)?.[1] ?? ""), "sitemap.xml");
} catch {
  // No prerendered sitemap in this build; the HTML assertions still stand.
}

if (origins.size === 0) {
  fail(["No canonical URL found in any prerendered page. Did the metadata stop emitting one?"]);
}

if (origins.size > 1) {
  fail([
    "The build advertises more than one origin:",
    ...[...origins].map(([origin, source]) => `- ${origin}  (e.g. ${source})`),
    "",
    "Every outbound URL must come from lib/site.ts getSiteUrl().",
  ]);
}

const [origin] = [...origins.keys()];

if (process.env.VERCEL_ENV === "production" && origin !== PRODUCTION_ORIGIN) {
  fail([
    `This production build would tell Google the site lives at ${origin}.`,
    `It lives at ${PRODUCTION_ORIGIN}.`,
    "",
    "A per-deployment *.vercel.app origin means getSiteUrl() fell through to",
    "VERCEL_URL, which changes on every deploy. Fix lib/site.ts or set",
    "NEXT_PUBLIC_SITE_URL on the project — do not ship this.",
  ]);
}

console.log(
  `Canonical origin verified: ${origin} across ${htmlFiles.length} prerendered page(s)${
    process.env.VERCEL_ENV ? ` (VERCEL_ENV=${process.env.VERCEL_ENV})` : ""
  }.`,
);
